"""Write ``tiny_polaris.yaml``: the generated Polaris config at test sizes, for the S6b loop / CLI tests.

    python tests/keras_native/s6b_fixtures/make_tiny_config.py      # any env with pyyaml; no keras / torch needed

Source: ``polaris/03_make_config.py`` with ``HGQ_PRECISION=32 HGQ_DEVICES=1 HGQ_ACCUM=2 HGQ_EBOPS_EVERY=2
HGQ_PID_WARMUP_EPOCHS=1`` and the PID setpoints below, then ``polaris/jax_common.shrink_config`` (dim 16, 2 heads, 1 + 1
layers, Linformer k 8, 64 nodes, 16 queries). Test-only changes: batch 4, no workers, 32 / 10 / 10 train / val / test
events (10 = 2 full val batches + a short one), 3 epochs, a log row every optimizer step, a 40x larger LR and pct_start 0.3 (so that a few
dummy-data steps lower the loss and the warm-up has more than one step), and repo-relative paths.
The PID target is 0.7x the tiny model's EBOPs at init
(1.12e8 at beta 1e-9, measured), so the controller moves beta inside its bounds instead of pinning it to a clamp.
"""

import os
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "polaris"))
from jax_common import shrink_config  # noqa: E402

ENV = {
    "HGQ_PRECISION": "32",
    "HGQ_DEVICES": "1",
    "HGQ_ACCUM": "2",
    "HGQ_EBOPS_EVERY": "2",
    "HGQ_PID_WARMUP_EPOCHS": "1",
    "HGQ_TARGET_EBOPS": "8e7",
    "HGQ_INIT_BETA": "5e-10",  # x HGQ_EBOPS_EVERY in the generated config: 1e-9
    "HGQ_MAX_BETA": "5e-7",
    "HGQ_MIN_BETA": "5e-13",
    "DATA_DIR": "/nonexistent/clic",  # dummy data only
    "CKPT_DIR": "/nonexistent/ckpts",  # not used by the native driver (run directory)
}


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "polaris_hgq.yaml"
        env = {**os.environ, **ENV, "HGQ_CONFIG_OUT": str(out)}
        subprocess.run([sys.executable, str(REPO / "polaris/03_make_config.py")], env=env, check=True, capture_output=True)
        cfg = yaml.safe_load(out.read_text())
    cfg = shrink_config(cfg, dim=16, heads=2, enc_layers=1, dec_layers=1, linformer_k=8, nodes=64, queries=16)
    cfg["name"] = "s6b_tiny"
    d = cfg["data"]
    d.update(
        batch_size=4,
        num_workers=0,
        num_train=32,
        num_val=10,
        num_test=10,
        scale_dict_path="src/hepattn/experiments/clic/configs/clic_var_transform.yaml",
    )
    t = cfg["trainer"]
    t.update(max_epochs=3, log_every_n_steps=1, accelerator="cpu")
    lrs = cfg["model"]["lrs_config"]
    lrs.update(initial=2e-4, max=2e-3, end=2e-5, pct_start=0.3)
    for task in cfg["model"]["model"]["init_args"]["tasks"]["init_args"]["modules"]:
        if "scale_dict_path" in task["init_args"]:
            task["init_args"]["scale_dict_path"] = d["scale_dict_path"]
    header = "# Generated by make_tiny_config.py (do not edit): the Polaris config at S6b test sizes.\n"
    (HERE / "tiny_polaris.yaml").write_text(header + yaml.safe_dump(cfg, sort_keys=False))


if __name__ == "__main__":
    main()
