"""Polaris configs for the first sectored-decoder comparison (issue #20): three arms, two seeds each.

Base: studies/linformer_dim/configs/small_linformer_lr6p2e-4_wd0p1_ep400_deck16.yaml (Lion 6.2e-4, weight decay 0.1,
400 epochs, global batch 2048, decoder Linformer k=16 in every arm). Polaris changes, the same in both arms: 4 A100s with 512 events each (global
batch 2048 as in the base), explicit DDP, host scipy matcher (the base's lap1015 extension and GPU jv solver are not
built there). The sector arms change only the decoder: 3 sectors of at most 53 nodes, 50 shared queries per sector
(3 x 50 = 150 as in the base), decoder linformer_seq_len 53. They differ only in the loss normalisation:
  ref     the base model
  sec3    sectored decoder, per-sector losses averaged with 1/3 (loss_norm: sector_mean)
  sec3ev  sectored decoder, reference losses on the event-frame outputs (loss_norm: event)
ref vs sec3ev isolates the architecture; sec3ev vs sec3 isolates the loss weighting.

    python studies/sector_decoder/make_configs.py   # from src/hepattn/experiments/clic
"""

import copy
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
BASE = HERE.parent / "linformer_dim/configs/small_linformer_lr6p2e-4_wd0p1_ep400_deck16.yaml"
OUT = HERE / "configs"
SEEDS = (42, 43)
ARMS = {"ref": None, "sec3": "sector_mean", "sec3ev": "event"}
NUM_SECTORS, NODES_PER_SECTOR = 3, 53  # 3 x 53 >= 159, the largest event the data selection keeps


def polaris(cfg):
    t = cfg["trainer"]
    t["devices"] = 4
    t["strategy"] = "ddp"
    cfg["data"]["batch_size"] = 512  # per GPU: 4 x 512 = 2048, the base's global batch
    cfg["data"]["num_workers"] = 8
    m = cfg["model"]["model"]["init_args"]["matcher"]["init_args"]
    m.pop("device_solver", None)
    m.update(default_solver="scipy", parallel_solver=True, n_jobs=8)


def sectored(cfg, loss_norm):
    cfg["data"]["sectors"] = {
        "num_sectors": NUM_SECTORS,
        "scheme": "cap",
        "max_nodes_per_sector": NODES_PER_SECTOR,
        "track_phi": "calo",
        "overflow": "drop_lowest_energy",
    }
    mm = cfg["model"]["model"]
    mm["class_path"] = "hepattn.models.sector.SectoredMaskFormer"
    mm["init_args"]["num_sectors"] = NUM_SECTORS
    mm["init_args"]["max_nodes_per_sector"] = NODES_PER_SECTOR
    mm["init_args"]["loss_norm"] = loss_norm
    dec = mm["init_args"]["decoder"]
    dec["num_queries"] = cfg["data"]["num_objects"] // NUM_SECTORS
    dec["decoder_layer_config"]["attn_kwargs"]["linformer_seq_len"] = max(NODES_PER_SECTOR, dec["num_queries"])


def main():
    text = BASE.read_text()
    base = yaml.safe_load(text)
    OUT.mkdir(exist_ok=True)
    for arm, loss_norm in ARMS.items():
        for seed in SEEDS:
            cfg = copy.deepcopy(base)
            polaris(cfg)
            if loss_norm is not None:
                sectored(cfg, loss_norm)
            cfg["name"] = f"clic_sector_{arm}_s{seed}"
            cfg["seed_everything"] = seed
            head = f"# Generated by studies/sector_decoder/make_configs.py from {BASE.relative_to(HERE.parent)}; do not edit.\n"
            (OUT / f"{arm}_s{seed}.yaml").write_text(head + yaml.safe_dump(cfg, sort_keys=False, width=120))
            print(OUT / f"{arm}_s{seed}.yaml")


if __name__ == "__main__":
    main()
